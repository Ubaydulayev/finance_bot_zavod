def _keyboard(items, callback_prefix, per_row=2):
    rows, row = [], []
    for item in items:
        row.append({"text": item, "callback_data": f"{callback_prefix}:{item}"})
        if len(row) == per_row:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    return {"inline_keyboard": rows}


